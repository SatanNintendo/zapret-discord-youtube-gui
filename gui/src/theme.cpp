void zg_theme_apply(int id)
{
    if (id < 0 || id >= ZG_THEME_COUNT) id = ZG_THEME_DARK;
    switch (id) {
    case ZG_THEME_LIGHT:    g_th = TH_LIGHT;    break;
    case ZG_THEME_MIDNIGHT: g_th = TH_MIDNIGHT; break;
    default:                g_th = TH_DARK;     break;
    }
    g_theme = id;
}
